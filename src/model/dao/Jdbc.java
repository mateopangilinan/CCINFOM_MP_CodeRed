package model.dao;

import exception.AppException;
import java.sql.*;
import java.time.LocalDate;

/**
 * Jdbc.java
 *
 * Provides the small JDBC operations repeated by DAOs: binding statement parameters, returning
 * generated IDs, checking changed rows and reading nullable values. It does not decide permissions
 * or commit transactions.
 */
final class Jdbc {
    private Jdbc() {}

    // Bind arguments to the question marks in order, keeping user values separate from SQL text.
    static PreparedStatement statement(Connection c, String sql, Object... args)
            throws SQLException {
        PreparedStatement p = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
        try {
            // Bind values as parameters rather than concatenating user input into SQL.
            // Match Java argument 0 to SQL placeholder 1, then continue in the same order.
            for (int i = 0; i < args.length; i++) p.setObject(i + 1, args[i]);
            return p;
        } catch (SQLException e) {
            p.close();
            throw e;
        }
    }

    // Execute the insert and return the ID generated by MySQL.
    static int insert(PreparedStatement p) throws SQLException {
        p.executeUpdate();
        try (ResultSet r = p.getGeneratedKeys()) {
            if (!r.next()) throw new SQLException("No generated ID");
            return r.getInt(1);
        }
    }

    // Require a changed row so an unavailable record is not reported as a successful edit.
    static void changed(PreparedStatement p) throws SQLException {
        // A scoped write must affect exactly one accessible record.
        if (p.executeUpdate() != 1)
            throw new AppException("Record not found or access denied. Refresh and retry.");
    }

    // Convert a SQL date to LocalDate while preserving a missing date as null.
    static LocalDate date(ResultSet r, String name) throws SQLException {
        Date d = r.getDate(name);
        if (d == null) {
            return null;
        } else {
            return d.toLocalDate();
        }
    }

    // Check wasNull so a missing SQL number does not accidentally become zero.
    static Integer integer(ResultSet r, String name) throws SQLException {
        int v = r.getInt(name);
        // JDBC returns zero for SQL NULL; preserve the distinction in the Java entity.
        if (r.wasNull()) {
            return null;
        } else {
            return v;
        }
    }
}
